"""Framework-agnostic pieces of predik_auth: config, signed tokens, signed links.

Token format (shared with the PHP broker, see broker/broker.php):

    v1.<base64url(json claims)>.<base64url(HMAC-SHA256(secret, "v1." + base64url(json claims)))>

The same format is used for the broker -> app hand-off (typ "broker", ~60 s, bound to a `state`
cookie) and for the app's own session cookie (typ "session", signed with a different secret).
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import time
from dataclasses import dataclass, field
from typing import Mapping

VERSION = "v1"
DEFAULT_BROKER_URL = "https://reports.predikdata.com/saml2/broker.php"
MIN_SECRET_LEN = 32
CLOCK_SKEW = 30  # seconds tolerated between the broker's clock and ours


class AuthError(Exception):
    """A token or link that must be rejected (bad signature, expired, wrong audience...)."""


class AuthConfigError(RuntimeError):
    """The app is misconfigured; raised at startup so it never runs without login."""


def _b64e(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def _b64d(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def _mac(secret: str, msg: str) -> bytes:
    return hmac.new(secret.encode(), msg.encode(), hashlib.sha256).digest()


def sign_token(secret: str, claims: dict) -> str:
    payload = _b64e(json.dumps(claims, separators=(",", ":"), ensure_ascii=False).encode())
    head = f"{VERSION}.{payload}"
    return f"{head}.{_b64e(_mac(secret, head))}"


def verify_token(secret: str, token: str, *, typ: str, aud: str | None = None, now: float | None = None) -> dict:
    """Return the claims of a valid, unexpired token of type `typ` (and audience `aud`), else raise AuthError."""
    try:
        ver, payload, sig = (token or "").split(".")
    except ValueError:
        raise AuthError("malformed token")
    if ver != VERSION:
        raise AuthError("unsupported token version")
    try:
        ok = hmac.compare_digest(_b64d(sig), _mac(secret, f"{ver}.{payload}"))
        claims = json.loads(_b64d(payload)) if ok else None
    except (ValueError, UnicodeDecodeError):
        raise AuthError("malformed token")
    if not ok or not isinstance(claims, dict):
        raise AuthError("bad signature")
    now = time.time() if now is None else now
    if claims.get("typ") != typ:
        raise AuthError("wrong token type")
    if aud is not None and claims.get("aud") != aud:
        raise AuthError("wrong audience")
    try:
        exp, iat = float(claims["exp"]), float(claims.get("iat", 0))
    except (KeyError, TypeError, ValueError):
        raise AuthError("missing expiry")
    if exp < now - CLOCK_SKEW or iat > now + CLOCK_SKEW:
        raise AuthError("expired")
    if not isinstance(claims.get("sub"), str) or not claims["sub"]:
        raise AuthError("missing subject")
    return claims


# ---------- signed links (bypass for links generated by the reports portal) ----------
def sign_link(secret: str, parts: list[str], exp: int | None = None) -> str:
    """Hex HMAC-SHA256 of "part1|part2|...[|exp]" (same as predik_link.php)."""
    msg = "|".join([*parts, *([str(int(exp))] if exp is not None else [])])
    return hmac.new(secret.encode(), msg.encode(), hashlib.sha256).hexdigest()


def verify_link(secret: str | None, sig: str | None, parts: list[str], exp: str | int | None = None,
                now: float | None = None) -> bool:
    """True if `sig` signs `parts` (and `exp`, when the link carries one, is still in the future)."""
    if not secret or not sig:
        return False
    exp_i = None
    if exp not in (None, ""):
        try:
            exp_i = int(exp)
        except (TypeError, ValueError):
            return False
        if exp_i < (time.time() if now is None else now):
            return False
    return hmac.compare_digest(sign_link(secret, parts, exp_i), str(sig).lower())


def safe_next(next_url: str | None) -> str:
    """Only same-site absolute paths ("/x?y"), never "//host" or "/\\host" (open redirect)."""
    n = (next_url or "").strip()
    if not n.startswith("/") or n.startswith("//") or n.startswith("/\\") or len(n) > 4096:
        return "/"
    if any(c in n for c in "\r\n\t"):
        return "/"
    return n


# ---------- configuration ----------
@dataclass(frozen=True)
class AuthConfig:
    """Read from env vars (see README). mode "sso" = login via the broker (default, mandatory in
    production); mode "dev" = everyone is AUTH_DEV_USER, only for local development."""

    mode: str = "sso"
    app_id: str = ""
    broker_url: str = DEFAULT_BROKER_URL
    broker_secret: str = ""
    session_secret: str = ""
    session_ttl: int = 12 * 3600
    allowed_domains: tuple[str, ...] = field(default_factory=tuple)
    dev_user: str = "dev@localhost"
    cookie_name: str = "pa_session"
    cookie_secure: bool = True

    @classmethod
    def from_env(cls, env: Mapping[str, str] | None = None) -> "AuthConfig":
        env = os.environ if env is None else env
        production = env.get("APP_ENV", "").lower() == "production"
        mode = (env.get("AUTH_MODE") or "sso").strip().lower()
        if mode not in ("sso", "dev"):
            raise AuthConfigError(f"AUTH_MODE must be 'sso' or 'dev', not {mode!r}")
        if mode == "dev":
            if production:
                raise AuthConfigError("AUTH_MODE=dev is not allowed with APP_ENV=production")
            return cls(mode="dev", dev_user=env.get("AUTH_DEV_USER") or "dev@localhost", cookie_secure=False)

        cfg = cls(
            mode="sso",
            app_id=(env.get("AUTH_APP_ID") or "").strip(),
            broker_url=(env.get("AUTH_BROKER_URL") or DEFAULT_BROKER_URL).strip(),
            broker_secret=env.get("AUTH_BROKER_SECRET") or "",
            session_secret=env.get("AUTH_SESSION_SECRET") or "",
            session_ttl=int(env.get("AUTH_SESSION_TTL_SECONDS") or 12 * 3600),
            allowed_domains=tuple(d.strip().lower().lstrip("@") for d in
                                  (env.get("AUTH_ALLOWED_EMAIL_DOMAINS") or "").split(",") if d.strip()),
            cookie_name=env.get("AUTH_COOKIE_NAME") or "pa_session",
            cookie_secure=(env.get("AUTH_COOKIE_SECURE") or "true").lower() != "false",
        )
        missing = [n for n, v in (("AUTH_APP_ID", cfg.app_id),) if not v]
        missing += [n for n, v in (("AUTH_BROKER_SECRET", cfg.broker_secret),
                                   ("AUTH_SESSION_SECRET", cfg.session_secret)) if len(v) < MIN_SECRET_LEN]
        if missing:
            raise AuthConfigError(
                "Login is mandatory: set " + ", ".join(missing)
                + f" (secrets >= {MIN_SECRET_LEN} chars), or AUTH_MODE=dev for local development only"
            )
        if production and not cfg.cookie_secure:
            raise AuthConfigError("AUTH_COOKIE_SECURE=false is not allowed with APP_ENV=production")
        return cfg

    def email_allowed(self, email: str) -> bool:
        return not self.allowed_domains or email.rsplit("@", 1)[-1].lower() in self.allowed_domains
